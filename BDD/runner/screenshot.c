typedef struct {
    char cells[TERM_ROWS][TERM_COLS];
    int row;
    int col;
} TermScreen;

static void screen_clear(TermScreen *s)
{
    for (int r = 0; r < TERM_ROWS; r++)
        for (int c = 0; c < TERM_COLS; c++)
            s->cells[r][c] = ' ';
    s->row = 0;
    s->col = 0;
}

static void screen_put(TermScreen *s, char ch)
{
    if (s->row < 0)
        s->row = 0;
    if (s->col < 0)
        s->col = 0;
    if (s->row >= TERM_ROWS)
        s->row = TERM_ROWS - 1;
    if (s->col >= TERM_COLS) {
        s->col = 0;
        if (s->row < TERM_ROWS - 1)
            s->row++;
    }
    if (ch == '\n') {
        s->col = 0;
        if (s->row < TERM_ROWS - 1)
            s->row++;
        return;
    }
    if (ch == '\r') {
        s->col = 0;
        return;
    }
    if (ch == '\b') {
        if (s->col > 0)
            s->col--;
        return;
    }
    if (ch < 32 || ch > 126)
        ch = ' ';
    s->cells[s->row][s->col] = ch;
    s->col++;
    if (s->col >= TERM_COLS) {
        s->col = 0;
        if (s->row < TERM_ROWS - 1)
            s->row++;
    }
}

static void screen_feed(TermScreen *s, const char *text)
{
    const char *p = text;
    while (*p) {
        if (*p == '\033' && p[1] == '[') {
            const char *q = p + 2;
            int n1 = 0, n2 = 0, have2 = 0, saw = 0;
            while (*q && !((*q >= '@' && *q <= 'Z') || (*q >= 'a' && *q <= 'z'))) {
                if (*q >= '0' && *q <= '9') {
                    if (!have2)
                        n1 = n1 * 10 + (*q - '0');
                    else
                        n2 = n2 * 10 + (*q - '0');
                    saw = 1;
                } else if (*q == ';') {
                    have2 = 1;
                }
                q++;
            }
            if (*q == 'J') {
                /* 2J = erase entire display */
                if (!saw || n1 == 2)
                    screen_clear(s);
            } else if (*q == 'H' || *q == 'f') {
                int row = have2 ? n1 : (saw ? n1 : 1);
                int col = have2 ? n2 : 1;
                if (row < 1)
                    row = 1;
                if (col < 1)
                    col = 1;
                s->row = row - 1;
                s->col = col - 1;
                if (s->row >= TERM_ROWS)
                    s->row = TERM_ROWS - 1;
                if (s->col >= TERM_COLS)
                    s->col = TERM_COLS - 1;
            } else if (*q == 'K') {
                for (int c = s->col; c < TERM_COLS; c++)
                    s->cells[s->row][c] = ' ';
            }
            p = *q ? q + 1 : q;
            continue;
        }
        screen_put(s, *p++);
    }
}

static int used_rows(const TermScreen *s)
{
    int last = 0;
    for (int r = 0; r < TERM_ROWS; r++) {
        for (int c = 0; c < TERM_COLS; c++) {
            if (s->cells[r][c] != ' ') {
                last = r;
                break;
            }
        }
    }
    return last + 1;
}

static int used_cols(const TermScreen *s, const int rows)
{
    int maxc = 40;
    for (int r = 0; r < rows; r++) {
        for (int c = TERM_COLS - 1; c >= 0; c--) {
            if (s->cells[r][c] != ' ') {
                if (c + 1 > maxc)
                    maxc = c + 1;
                break;
            }
        }
    }
    if (maxc > TERM_COLS)
        maxc = TERM_COLS;
    return maxc;
}

static void blit_glyph(unsigned char *img, const int img_w, const int x, const int y, char ch,
                       const unsigned char fr, const unsigned char fg, const unsigned char fb)
{
    if (ch < 32 || ch > 126)
        ch = '?';
    const int gi = ch - 32;
    for (int row = 0; row < GLYPH_H; row++) {
        const unsigned char bits = FONT8X16[gi][row];
        for (int col = 0; col < GLYPH_W; col++) {
            if (bits & (0x80 >> col)) {
                for (int sy = 0; sy < SCALE; sy++) {
                    for (int sx = 0; sx < SCALE; sx++) {
                        const int px = x + col * SCALE + sx;
                        const int py = y + row * SCALE + sy;
                        const int off = (py * img_w + px) * 3;
                        img[off] = fr;
                        img[off + 1] = fg;
                        img[off + 2] = fb;
                    }
                }
            }
        }
    }
}

static unsigned long crc_table[256];
static int crc_ready;

static void crc_init(void)
{
    if (crc_ready)
        return;
    for (int n = 0; n < 256; n++) {
        unsigned long c = (unsigned long)n;
        for (int k = 0; k < 8; k++)
            c = (c & 1) ? (0xedb88320UL ^ (c >> 1)) : (c >> 1);
        crc_table[n] = c;
    }
    crc_ready = 1;
}

static int write_chunk(FILE *fp, const char *type, const unsigned char *data, const size_t len)
{
    unsigned char lenb[4], crcbuf[4], typed[4];
    size_t i;

    lenb[0] = (unsigned char)((len >> 24) & 0xff);
    lenb[1] = (unsigned char)((len >> 16) & 0xff);
    lenb[2] = (unsigned char)((len >> 8) & 0xff);
    lenb[3] = (unsigned char)(len & 0xff);
    memcpy(typed, type, 4);
    if (fwrite(lenb, 1, 4, fp) != 4 || fwrite(typed, 1, 4, fp) != 4)
        return -1;
    if (len && data && fwrite(data, 1, len, fp) != len)
        return -1;
    crc_init();
    unsigned long crc = 0xffffffffUL;
    for (i = 0; i < 4; i++)
        crc = crc_table[(crc ^ typed[i]) & 0xff] ^ (crc >> 8);
    for (i = 0; i < len; i++)
        crc = crc_table[(crc ^ data[i]) & 0xff] ^ (crc >> 8);
    crc ^= 0xffffffffUL;
    crcbuf[0] = (unsigned char)((crc >> 24) & 0xff);
    crcbuf[1] = (unsigned char)((crc >> 16) & 0xff);
    crcbuf[2] = (unsigned char)((crc >> 8) & 0xff);
    crcbuf[3] = (unsigned char)(crc & 0xff);
    return fwrite(crcbuf, 1, 4, fp) == 4 ? 0 : -1;
}

static unsigned long screen_hash(const TermScreen *s)
{
    unsigned long h = 2166136261UL;
    const int rows = used_rows(s);
    const int cols = used_cols(s, rows);

    for (int r = 0; r < rows; r++) {
        for (int c = 0; c < cols; c++) {
            h ^= (unsigned char)s->cells[r][c];
            h *= 16777619UL;
        }
        h ^= '\n';
        h *= 16777619UL;
    }
    return h;
}

static int screenshot_write_from_screen(const TermScreen *screen, const char *path)
{
    int r;
    unsigned char *zbuf = NULL;
    uLongf zlen;
    FILE *fp = NULL;
    int rc = -1;
    unsigned char ihdr[13];
    const unsigned char sig[8] = {137, 80, 78, 71, 13, 10, 26, 10};
    const unsigned char bg[3] = {30, 30, 30};
    const unsigned char fg[3] = {220, 220, 220};

    int rows = used_rows(screen);
    const int cols = used_cols(screen, rows);
    
    if (rows < 8)
        rows = 8;

    const int img_w = cols * GLYPH_W * SCALE + PAD * 2;
    const int img_h = rows * GLYPH_H * SCALE + PAD * 2;
    
    unsigned char* img = malloc((size_t)img_w * (size_t)img_h * 3);
    
    if (!img)
        return -1;
    
    for (r = 0; r < img_w * img_h; r++) {
        img[r * 3] = bg[0];
        img[r * 3 + 1] = bg[1];
        img[r * 3 + 2] = bg[2];
    }

    for (r = 0; r < rows; r++) {
        for (int c = 0; c < cols; c++) {
            const char ch = screen->cells[r][c];
            if (ch == ' ')
                continue;
            blit_glyph(img, img_w,
                       PAD + c * GLYPH_W * SCALE,
                       PAD + r * GLYPH_H * SCALE,
                       ch, fg[0], fg[1], fg[2]);
        }
    }

    unsigned char* raw = malloc((size_t)(img_w * 3 + 1) * (size_t)img_h);
    
    if (!raw)
        goto done;
    
    for (r = 0; r < img_h; r++) {
        raw[r * (img_w * 3 + 1)] = 0;
        memcpy(raw + r * (img_w * 3 + 1) + 1, img + r * img_w * 3, (size_t)img_w * 3);
    }

    zlen = compressBound((uLong)((img_w * 3 + 1) * img_h));
    zbuf = (unsigned char *)malloc(zlen);
    
    if (!zbuf)
        goto done;
    
    if (compress2(zbuf, &zlen, raw, (uLong)((img_w * 3 + 1) * img_h), 9) != Z_OK)
        goto done;

    fp = fopen(path, "wb");
    
    if (!fp)
        goto done;
    
    if (fwrite(sig, 1, 8, fp) != 8)
        goto done;
    
    ihdr[0] = (unsigned char)((img_w >> 24) & 0xff);
    ihdr[1] = (unsigned char)((img_w >> 16) & 0xff);
    ihdr[2] = (unsigned char)((img_w >> 8) & 0xff);
    ihdr[3] = (unsigned char)(img_w & 0xff);
    ihdr[4] = (unsigned char)((img_h >> 24) & 0xff);
    ihdr[5] = (unsigned char)((img_h >> 16) & 0xff);
    ihdr[6] = (unsigned char)((img_h >> 8) & 0xff);
    ihdr[7] = (unsigned char)(img_h & 0xff);
    ihdr[8] = 8;
    ihdr[9] = 2;
    ihdr[10] = 0;
    ihdr[11] = 0;
    ihdr[12] = 0;
    
    if (write_chunk(fp, "IHDR", ihdr, 13) != 0)
        goto done;
    
    if (write_chunk(fp, "IDAT", zbuf, zlen) != 0)
        goto done;
    
    if (write_chunk(fp, "IEND", NULL, 0) != 0)
        goto done;
    
    rc = 0;

done:
    if (fp)
        fclose(fp);
    free(zbuf);
    free(raw);
    free(img);
    return rc;
}

int screenshot_write_png(const char *text, const char *path)
{
    TermScreen screen;

    if (!text || !path)
        return -1;
    screen_clear(&screen);
    screen_feed(&screen, text);
    return screenshot_write_from_screen(&screen, path);
}

int screenshot_write_png_unique(const char *text, const char *path,
                                unsigned long *last_hash)
{
    TermScreen screen;

    if (!text || !path || !last_hash)
        return -1;
    screen_clear(&screen);
    screen_feed(&screen, text);
    const unsigned long h = screen_hash(&screen);
    if (*last_hash != 0 && h == *last_hash)
        return 1;
    if (screenshot_write_from_screen(&screen, path) != 0)
        return -1;
    *last_hash = h;
    return 0;
}
